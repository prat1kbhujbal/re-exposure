/*
 * seal -- build-time asset sealer for the key-as-lock model.
 *
 * Encrypts a protected asset under a key derived from the developer's license
 * key, and emits a C header the application embeds. The license key is a BUILD
 * input; it is never written into the header or the binary. At runtime the
 * application re-derives the same key from the key the *user* supplies and
 * decrypts the asset. A wrong key fails the GCM tag, so no plaintext is ever
 * produced -- there is no success branch to patch, unlike a license *gate*.
 *
 * Real primitives (OpenSSL): PBKDF2-HMAC-SHA256 for key stretching, AES-256-GCM
 * for authenticated encryption. Not a hand-rolled cipher.
 *
 *   seal <asset-file> <license-key>  > build/locked.h
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <openssl/evp.h>
#include <openssl/rand.h>

#define ITERS 200000
#define SALT_LEN 16
#define IV_LEN 12
#define TAG_LEN 16

static void die(const char *m) { fprintf(stderr, "seal: %s\n", m); exit(1); }

static void emit(const char *name, const unsigned char *b, int n) {
    printf("static const unsigned char %s[%d] = {", name, n);
    for (int i = 0; i < n; i++)
        printf("%s0x%02x,", (i % 12 == 0) ? "\n    " : "", b[i]);
    printf("\n};\n");
}

int main(int argc, char **argv) {
    if (argc < 3)
        die("usage: seal <asset-file> <license-key>");

    FILE *f = fopen(argv[1], "rb");
    if (!f) die("cannot open asset file");
    fseek(f, 0, SEEK_END);
    long n = ftell(f);
    fseek(f, 0, SEEK_SET);
    unsigned char *pt = malloc(n);
    if (fread(pt, 1, n, f) != (size_t)n) die("short read");
    fclose(f);

    unsigned char salt[SALT_LEN], iv[IV_LEN], key[32], tag[TAG_LEN];
    if (!RAND_bytes(salt, SALT_LEN) || !RAND_bytes(iv, IV_LEN))
        die("RAND_bytes failed");

    if (!PKCS5_PBKDF2_HMAC(argv[2], strlen(argv[2]), salt, SALT_LEN, ITERS,
                           EVP_sha256(), 32, key))
        die("PBKDF2 failed");

    unsigned char *ct = malloc(n + 16);
    int outl = 0, tmpl = 0;
    EVP_CIPHER_CTX *c = EVP_CIPHER_CTX_new();
    EVP_EncryptInit_ex(c, EVP_aes_256_gcm(), NULL, NULL, NULL);
    EVP_CIPHER_CTX_ctrl(c, EVP_CTRL_GCM_SET_IVLEN, IV_LEN, NULL);
    EVP_EncryptInit_ex(c, NULL, NULL, key, iv);
    EVP_EncryptUpdate(c, ct, &outl, pt, n);
    EVP_EncryptFinal_ex(c, ct + outl, &tmpl);
    EVP_CIPHER_CTX_ctrl(c, EVP_CTRL_GCM_GET_TAG, TAG_LEN, tag);
    EVP_CIPHER_CTX_free(c);

    printf("/* generated by tools/seal.c -- the license key is NOT here */\n");
    printf("#define PBKDF2_ITERS %d\n", ITERS);
    printf("static const int CT_LEN = %d;\n", outl);
    emit("SEAL_SALT", salt, SALT_LEN);
    emit("SEAL_IV", iv, IV_LEN);
    emit("SEAL_TAG", tag, TAG_LEN);
    emit("SEAL_CT", ct, outl);

    free(pt);
    free(ct);
    return 0;
}
