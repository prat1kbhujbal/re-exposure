#!/usr/bin/env python3
"""Build-time secret encryptor.

Reads a plaintext strings file (one per line) and emits a C header with
each secret stored as XOR-obfuscated bytes under a rolling key. The plaintext
never lands in the shipped binary's .rodata, so `strings` and xref search
find nothing. XOR is intentionally weak crypto -- the point of THIS layer is
to kill signature/landmark search, not to resist a memory dump. (That is what
the later runtime layers are for.)

Usage: gen_secrets.py <strings.txt> <out_header.h>
"""
import sys

# Rolling key. In a real build you would generate this per-build and keep it
# out of source control; hardcoded here so the lab is reproducible.
KEY = bytes([0x5A, 0xA5, 0x3C, 0xC3, 0x17, 0x71, 0x2E, 0xE2])


def enc(data: bytes) -> bytes:
    return bytes(b ^ KEY[i % len(KEY)] for i, b in enumerate(data))


def main() -> int:
    src, out = sys.argv[1], sys.argv[2]
    with open(src, "rb") as fh:
        lines = [ln.rstrip(b"\n") for ln in fh if ln.strip()]

    with open(out, "w") as fh:
        fh.write("/* GENERATED by gen_secrets.py -- do not edit. */\n")
        fh.write("#ifndef SECRETS_ENC_H\n#define SECRETS_ENC_H\n\n")
        fh.write("#include <stddef.h>\n\n")
        # `volatile` forces real loads so the optimizer cannot constant-fold
        # the XOR and reconstruct the plaintext in .rodata (see README note).
        fh.write("static const volatile unsigned char SEC_KEY[] = {")
        fh.write(",".join(f"0x{b:02x}" for b in KEY))
        fh.write("};\n")
        fh.write(f"#define SEC_KEY_LEN {len(KEY)}\n\n")
        for idx, line in enumerate(lines):
            blob = enc(line)
            fh.write(f"/* secret {idx}: {len(line)} bytes, encrypted */\n")
            fh.write(f"static const volatile unsigned char SEC_{idx}[] = {{")
            fh.write(",".join(f"0x{b:02x}" for b in blob))
            fh.write("};\n")
            fh.write(f"#define SEC_{idx}_LEN {len(blob)}\n\n")
        fh.write("#endif\n")
    print(f"wrote {out}: {len(lines)} secrets encrypted")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
